#Requires -Version 5.1
<#
.SYNOPSIS
  Native-Windows herdr config from the WSL dotfiles checkout. Nothing else.

.DESCRIPTION
  The one source is the WSL dotfiles checkout (~/dotfiles), the same files WSL
  herdr reads through stow. Run this script from that checkout's path
  (\\wsl.localhost\<distro>\home\<user>\dotfiles\install.ps1); the WSL
  install.sh does so itself. Never run it from a separate Windows clone: that
  clone drifts from what WSL herdr draws.

  Windows herdr reads %APPDATA%\herdr\config.toml (not ~/.config/herdr) and
  TOML has no include, so this GENERATES that file from two sources:

    herdr\.config\herdr\config.toml   shared with WSL: prefix, pane navigation,
                                      sidebar rows, theme. Identical bytes on
                                      both sides.
    herdr\windows\terminal.toml       Windows-only [terminal] table: Git Bash as
                                      the default shell, since native herdr has no
                                      $SHELL to fall back on and would spawn cmd.exe.

  Then runs `herdr config check` on the generated file and, when it is the live
  %APPDATA% path, `herdr server reload-config` so the running server picks it
  up. Idempotent; re-run after any change to either source. A hand-written
  config.toml is backed up once to config.toml.pre-dotfiles before being replaced.

.PARAMETER Destination
  Where to write the generated config. Defaults to %APPDATA%\herdr\config.toml.
  Any other path is written and checked but never reloaded into the server.
#>
[CmdletBinding()]
param(
    [string]$Destination = (Join-Path $env:APPDATA 'herdr\config.toml')
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$Dotfiles = $PSScriptRoot
$shared   = Join-Path $Dotfiles 'herdr\.config\herdr\config.toml'
$tail     = Join-Path $Dotfiles 'herdr\windows\terminal.toml'
$dest     = $Destination
$dir      = Split-Path -Parent $dest
$live     = Join-Path $env:APPDATA 'herdr\config.toml'
$marker   = '# GENERATED by dotfiles\install.ps1'

function Say($msg) { Write-Host "==> $msg" }

$header = @(
    $marker
    "# Sources: herdr\.config\herdr\config.toml + herdr\windows\terminal.toml"
    "# in the WSL dotfiles checkout $Dotfiles"
    "# Edit those and re-run install.sh (or install.ps1); edits here are overwritten."
    ''
) -join "`n"

$new = ($header + (Get-Content -LiteralPath $shared -Raw) + (Get-Content -LiteralPath $tail -Raw)) -replace "`r`n", "`n"

if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }

$current = if (Test-Path -LiteralPath $dest) { Get-Content -LiteralPath $dest -Raw } else { $null }
if ($current -eq $new) {
    Say "herdr config already current: $dest"
} else {
    if ($null -ne $current -and -not $current.StartsWith($marker)) {
        Copy-Item -LiteralPath $dest -Destination "$dest.pre-dotfiles" -Force
        Say "Backed up hand-written herdr config to $dest.pre-dotfiles"
    }
    [IO.File]::WriteAllText($dest, $new, [Text.UTF8Encoding]::new($false))
    Say "Wrote $dest"
}

if (Get-Command herdr -ErrorAction SilentlyContinue) {
    $env:HERDR_CONFIG_PATH = $dest
    try { $check = & herdr config check 2>&1; $checkExit = $LASTEXITCODE }
    finally { Remove-Item Env:HERDR_CONFIG_PATH }
    Write-Host "    herdr config check: $($check -join ' | ')"
    if ($checkExit -ne 0) { throw "herdr config check failed on $dest" }

    if ([IO.Path]::GetFullPath($dest) -ne [IO.Path]::GetFullPath($live)) {
        Say "Not the live config; skipping herdr server reload-config"
    } else {
        $reload = & herdr server reload-config 2>&1
        if ($LASTEXITCODE -eq 0) { Say "herdr server reloaded config" }
        else { Write-Host "    (no running herdr server to reload: $($reload -join ' '))" }
    }
} else {
    Write-Warning "herdr not on PATH; install from https://herdr.dev then re-run."
}
